#!/usr/bin/env python3
"""Kernel-category table for the report, from torch.profiler XPU traces.

Writes report/generated/tab_kernel.tex.
  Omni:  results/20261124_kprof2/omni-t2i-cfgpar2/prof  (single-stage CFG parallel, cards 0,1; one denoise step, rank 0;
         the 5 s oneccl stall is excluded)
  M*:    results/20261125_kprof3/mstar-t2i-cfgpar/prof  (CFG parallel, cards 0,1,2; rank 0; 0.45 s window; partial, shares only)
Uses only the standard library (python3 -I).
"""
import glob
import gzip
import json
from collections import defaultdict
from pathlib import Path

WS = Path(__file__).resolve().parents[1]
OUT = WS / "report" / "generated" / "tab_kernel.tex"
OMNI = WS / "results/20261124_kprof2/omni-t2i-cfgpar2/prof"
MSTAR = WS / "results/20261125_kprof3/mstar-t2i-cfgpar/prof"

CATS = ["gemm", "attention", "fused", "index", "copy", "rmsnorm", "other"]
CAT_NAME = {"gemm": "gemm（矩阵乘）", "attention": "attention（FMHA）",
            "fused": "融合 kernel（Triton / vLLM）", "index": "index、gather、scatter",
            "copy": "copy、cat", "rmsnorm": "RMSNorm 拆散部分（pow、mean、reduce）", "other": "其他 elementwise"}


def classify(name):
    if "gemm" in name:
        return "gemm"
    if "fmha" in name:
        return "attention"
    if name.startswith(("triton", "vllm")):
        return "fused"
    if any(k in name for k in ("IndexPut", "IndexKernel", "Gather", "IndexSelect")):
        return "index"
    if any(k in name for k in ("Copy", "Memcpy", "Cat")):
        return "copy"
    if any(k in name for k in ("Reduce", "Pow", "Mean")):
        return "rmsnorm"
    return "other"


def rank0_kernels(prof_dir, drop_ccl=False):
    """kernel events of the trace file with the most kernels (= rank 0 of the profiled server)"""
    best = []
    for p in glob.glob(str(prof_dir / "trace_*.json.gz")):
        ks = [e for e in json.load(gzip.open(p))["traceEvents"]
              if e.get("ph") == "X" and e.get("cat") == "kernel"]
        if len(ks) > len(best):
            best = ks
    if drop_ccl:
        # keep the kernels before the first oneCCL stall (profiler-induced wait); later kernels are outside the step
        stall = min(e["ts"] for e in best if "ccl" in e["name"].lower())
        best = [e for e in best if e["ts"] < stall and "ccl" not in e["name"].lower()]
    return sorted(best, key=lambda e: e["ts"])


def summarize(ks):
    tot = defaultdict(float)
    cnt = defaultdict(int)
    for e in ks:
        c = classify(e["name"])
        tot[c] += e["dur"]
        cnt[c] += 1
    busy = sum(tot.values())
    span = ks[-1]["ts"] + ks[-1]["dur"] - ks[0]["ts"]
    gemm_n = cnt["gemm"]
    return dict(tot=tot, cnt=cnt, busy=busy, span=span, gemm_avg=tot["gemm"] / gemm_n if gemm_n else 0.0,
                n=len(ks))


omni = summarize(rank0_kernels(OMNI, drop_ccl=True))
mstar = summarize(rank0_kernels(MSTAR))


def ms(us):
    return f"{us / 1e3:.1f}"


def pc(x, tot):
    return f"{100 * x / tot:.1f}\\%"


L = ["% generated by scripts/make_kernel_table.py -- do not edit",
     "\\scriptsize\\setlength{\\tabcolsep}{2.5pt}",
     "\\begin{tabularx}{\\textwidth}{>{\\bfseries}p{5.0cm} r r r r r}",
     "\\toprule", "\\rowcolor{Mist}",
     "kernel 类别 & Omni ms & Omni 占比 & Omni 次数 & M* 占比 & M* 次数 \\\\", "\\midrule"]
for c in CATS:
    L.append(f"{CAT_NAME[c]} & {ms(omni['tot'][c])} & {pc(omni['tot'][c], omni['busy'])} & {omni['cnt'][c]} & "
             f"{pc(mstar['tot'][c], mstar['busy'])} & {mstar['cnt'][c]} \\\\")
L += ["\\midrule",
      f"合计（kernel 忙碌时间） & {ms(omni['busy'])} & 100\\% & {omni['n']} & 100\\% & {mstar['n']} \\\\",
      f"窗口时长 & {ms(omni['span'])} & & & {ms(mstar['span'])} & \\\\",
      f"空闲（窗口 − 忙碌） & {ms(omni['span'] - omni['busy'])} & {pc(omni['span'] - omni['busy'], omni['span'])} & & "
      f"{pc(mstar['span'] - mstar['busy'], mstar['span'])} & \\\\",
      f"gemm 平均耗时（ms） & {omni['gemm_avg'] / 1e3:.2f} & & & {mstar['gemm_avg'] / 1e3:.2f} & \\\\",
      "\\bottomrule", "\\end{tabularx}"]
OUT.write_text("\n".join(L) + "\n")
print("wrote", OUT.name)
